// forge2c - Translate Forge (.fge) to C/C++
// Generates portable C code from Forge source

#include <iostream>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>
#include <regex>

std::string readFile(const std::string& path) {
    std::ifstream f(path);
    if (!f) return "";
    std::stringstream ss;
    ss << f.rdbuf();
    return ss.str();
}

std::string translateToC(const std::string& code, const std::string& name) {
    std::string out = code;
    
    std::stringstream result;
    result << "/* Generated by forge2c from Forge */\n";
    result << "/* Source: " << name << " */\n";
    result << "/* WARNING: Generated code may need manual adjustment */\n\n";
    result << "#include <stdio.h>\n";
    result << "#include <stdlib.h>\n";
    result << "#include <string.h>\n\n";
    
    // fn -> function
    out = std::regex_replace(out, std::regex("fn\\s+(\\w+)\\s*\\("), "int $1(");
    out = std::regex_replace(out, std::regex("\\blet\\s+(\\w+)\\s*=\\s*([^;\\n]+)"), "auto $1 = $2;");
    out = std::regex_replace(out, std::regex("\\bconst\\s+(\\w+)\\s*=\\s*([^;\\n]+)"), "const auto $1 = $2;");
    out = std::regex_replace(out, std::regex("\\bprint\\s*\\("), "printf(");
    out = std::regex_replace(out, std::regex("\\bnil\\b"), "NULL");
    out = std::regex_replace(out, std::regex("\\btrue\\b"), "1");
    out = std::regex_replace(out, std::regex("\\bfalse\\b"), "0");
    
    // Add semicolons where missing (basic)
    result << out << "\n";
    
    return result.str();
}

int main(int argc, char** argv) {
    if (argc < 2) {
        std::cout << "forge2c - Translate Forge (.fge) to C/C++\n\n";
        std::cout << "Usage: forge2c <input.fge> [output.c|output.cpp]\n";
        std::cout << "       forge2c --runtime  Generate Forge runtime header\n";
        return 1;
    }
    
    std::string input = argv[1];
    if (input == "--runtime") {
        std::cout << "[forge2c] Generating runtime header...\n";
        std::ofstream h("forge_runtime.h");
        h << "#ifndef FORGE_RUNTIME_H\n#define FORGE_RUNTIME_H\n\n";
        h << "#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n\n";
        h << "typedef struct { char* data; int len; } ForgeString;\n";
        h << "#define print(x) printf(\"%s\\n\", (x))\n\n";
        h << "#endif\n";
        std::cout << "[forge2c] Wrote forge_runtime.h\n";
        return 0;
    }
    
    std::string output;
    if (argc >= 3) {
        output = argv[2];
    } else {
        size_t dot = input.find_last_of(".");
        if (dot != std::string::npos) {
            output = input.substr(0, dot) + ".c";
        } else {
            output = input + ".c";
        }
    }
    
    std::string code = readFile(input);
    if (code.empty()) {
        std::cerr << "[forge2c] Error: Cannot read " << input << "\n";
        return 1;
    }
    
    std::string translated = translateToC(code, input);
    
    std::ofstream out(output);
    if (!out) {
        std::cerr << "[forge2c] Error: Cannot write " << output << "\n";
        return 1;
    }
    out << translated;
    
    std::cout << "[forge2c] " << input << " -> " << output << "\n";
    return 0;
}
