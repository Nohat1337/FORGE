int main(int argc, char** argv) {
    print_banner();
    
    if (argc < 2) {
        std::cout << "\033[1mUsage:\033[0m cfmake [options] <project_name>\n\n";
        std::cout << "\033[1mOptions:\033[0m\n";
        std::cout << "  init <name>        Initialize new Forge project\n";
        std::cout << "  configure          Generate ForgeLists.txt from source\n";
        std::cout << "  generate           Create build files\n";
        std::cout << "  wizard             Interactive project wizard\n\n";
        std::cout << "\033[1mExamples:\033[0m\n";
        std::cout << "  cfmake init MyApp\n";
        std::cout << "  cfmake configure\n";
        std::cout << "  cfmake wizard\n";
        return 1;
    }
    
    std::string cmd = argv[1];
    
    if (cmd == "init" && argc >= 3) {
        std::string name = argv[2];
        std::cout << "[*] Creating Forge project: " << name << "\n\n";
        
        fs::create_directories(name + "/src");
        fs::create_directories(name + "/lib");
        fs::create_directories(name + "/tests");
        fs::create_directories(name + "/assets");
        
        std::ofstream fl(name + "/ForgeLists.txt");
        fl << "# ForgeLists.txt - Generated by CFMAKE\n";
        fl << "project(" << name << ")\n";
        fl << "version(1.0.0)\n";
        fl << "source(src)\n";
        fl << "include(include)\n";
        fl << "output(" << name << ")\n";
        fl << "arch(x64)\n";
        fl << "type(executable)\n";
        fl << "# target(android|linux|windows|darwin)\n";
        fl.close();
        
        std::ofstream main(name + "/src/main.fge");
        main << "// " << name << " - Main entry point\n\n";
        main << "fn main() {\n";
        main << "  print(\"Hello from " << name << "!\")\n";
        main << "}\n\n";
        main << "main()\n";
        main.close();
        
        std::ofstream readme(name + "/README.md");
        readme << "# " << name << "\n\nBuilt with Forge using CFMAKE.\n\n## Build\n```bash\ncfmake configure\nforgevm build\n```\n";
        readme.close();
        
        std::ofstream cf(name + "/CFMakeLists.txt");
        cf << "# CFMake configuration\n";
        cf << "cmake_minimum_required(VERSION 1.0)\n";
        cf << "project(" << name << ")\n";
        cf << "\n";
        cf << "set(SOURCES\n";
        cf << "    src/main.fge\n";
        cf << ")\n";
        cf << "\n";
        cf << "add_executable(" << name << " ${SOURCES})\n";
        cf.close();
        
        std::cout << "[✓] Created " << name << "/\n";
        std::cout << "[✓] ForgeLists.txt\n";
        std::cout << "[✓] CFMakeLists.txt\n";
        std::cout << "[✓] src/main.fge\n\n";
        std::cout << "[*] Build: cd " << name << " && forgevm build\n";
        return 0;
    }
    
    if (cmd == "configure") {
        std::cout << "[*] CFMAKE Configuring...\n";
        
        if (!fs::exists("CFMakeLists.txt")) {
            std::cout << "[!] No CFMakeLists.txt found. Creating one...\n";
            std::ofstream cf("CFMakeLists.txt");
            cf << "project(AutoForge)\n";
            cf << "version(1.0.0)\n\n";
            cf << "file(GLOB_RECURSE FORGE_SOURCES src/*.fge)\n\n";
            cf << "add_executable(app ${FORGE_SOURCES})\n";
            cf.close();
        }
        
        std::vector<std::string> sources;
        if (fs::exists("src")) {
            for (const auto& e : fs::recursive_directory_iterator("src")) {
                if (e.is_regular_file() && e.path().extension() == ".fge") {
                    sources.push_back(e.path().string());
                    std::cout << "  [+] " << e.path().string() << "\n";
                }
            }
        }
        
        std::ofstream fl("ForgeLists.txt");
        fl << "# Auto-generated by CFMAKE\n";
        fl << "project(AutoForge)\n";
        fl << "version(1.0.0)\n";
        fl << "source(src)\n";
        fl << "output(app)\n";
        fl << "arch(x64)\n";
        fl << "type(executable)\n\n";
        for (auto& s : sources) {
            fl << "file(" << s << ")\n";
        }
        fl.close();
        
        std::cout << "\n[✓] ForgeLists.txt generated\n";
        std::cout << "[✓] Found " << sources.size() << " source file(s)\n";
        std::cout << "[*] Run: forgevm build\n";
        return 0;
    }
    
    if (cmd == "wizard") {
        std::cout << "[*] Interactive Project Wizard\n\n";
        std::string name, type;
        std::cout << "Project name: ";
        std::getline(std::cin, name);
        std::cout << "Type (executable/library/shared): ";
        std::getline(std::cin, type);
        if (type.empty()) type = "executable";
        
        // Call init logic
        fs::create_directories(name + "/src");
        std::ofstream fl(name + "/ForgeLists.txt");
        fl << "project(" << name << ")\nversion(1.0.0)\nsource(src)\noutput(" << name << ")\ntype(" << type << ")\narch(x64)\n";
        fl.close();
        std::ofstream main(name + "/src/main.fge");
        main << "fn main() { print(\"" << name << " initialized\") }\nmain()\n";
        main.close();
        std::cout << "\n[✓] Project created: " << name << "/\n";
        return 0;
    }
    
    std::cout << "[!] Unknown command\n";
    return 1;
}
